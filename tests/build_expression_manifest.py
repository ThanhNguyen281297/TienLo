"""Read generated atlas geometry and write metadata only; never alter PNG pixels.

Optional authoring dependency: Pillow. Production and CI consume the committed JSON.
Each frame is a complete character, not a face/head fragment.
"""
import json
from statistics import median
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
# The illustrator's registration guides are deliberately outside source rectangles.
GRIDS = {
    'Kiem/Nam': ([6,232,459,686,913,1140,1366], [6,234,461,688,916,1133]),
    'Kiem/Nu': ([0,211,426,688,899,1121,1374], [0,235,468,701,930,1142]),
    'Liem/Nam': ([2,231,459,688,916,1145,1373], [2,253,496,734,961,1141]),
    'Liem/Nu': ([1,231,458,688,918,1146,1374], [1,231,459,688,916,1142]),
    'Thuong/Nam': ([0,230,459,687,917,1146,1373], [1,235,467,692,918,1142]),
    'Thuong/Nu': ([0,229,458,688,917,1147,1375], [0,246,487,725,952,1142]),
    'Quat/Nam': ([4,232,459,687,915,1143,1370], [1,235,464,692,920,1142]),
    'Quat/Nu': ([1,229,458,688,917,1145,1374], [1,236,467,696,925,1142]),
}

def measure(image, rect):
    """Locate the full connected body and its floor anchor, without editing it."""
    x0,y0,w,h=rect
    pixels=image.load()
    remaining={(x,y) for y in range(h) for x in range(w) if pixels[x0+x,y0+y][3]>160}
    largest=[]
    while remaining:
        start=remaining.pop(); queue=[start]
        for x,y in queue:
            for point in ((x-1,y),(x+1,y),(x,y-1),(x,y+1)):
                if point in remaining:
                    remaining.remove(point); queue.append(point)
        if len(queue)>len(largest): largest=queue
    assert len(largest)>1000, rect
    xs=[p[0] for p in largest]; ys=[p[1] for p in largest]
    left=max(0,min(xs)-2); top=max(0,min(ys)-2)
    right=min(w,max(xs)+3); bottom=min(h,max(ys)+3)
    floor_y=max(ys)
    floor=sorted(x for x,y in largest if y>=floor_y-3)
    anchor=[floor[len(floor)//2]-left,floor_y+1-top]
    return [x0+left,y0+top,right-left,bottom-top],anchor

def main():
    atlases={}
    for name,(xs,ys) in GRIDS.items():
        file='Character/Expressions/'+name+'.png'
        image=Image.open(ROOT/file).convert('RGBA')
        frames=[]
        for variant in range(1,11):
            row=(variant-1)//2; base=((variant-1)%2)*3
            for offset,direction in enumerate(('truoc','trai','phai')):
                col=base+offset
                cell=[xs[col]+4,ys[row]+4,xs[col+1]-xs[col]-8,ys[row+1]-ys[row]-8]
                rect,anchor=measure(image,cell)
                frames.append(dict(variant=variant,direction=direction,rect=rect,anchor=anchor))
        # The illustrator compressed the final row of two sheets vertically.
        # Restore the complete figure's aspect at draw time, never retarget a face.
        for direction in ('truoc','trai','phai'):
            reference=median(f['rect'][2]/f['anchor'][1] for f in frames if f['direction']==direction and f['variant']<=8)
            for frame in frames:
                if frame['direction']!=direction: continue
                ratio=frame['rect'][2]/frame['anchor'][1]
                frame['pixelAspect']=round(reference/ratio,6) if ratio>reference*1.2 else 1
        atlases[name]=dict(file=file,size=list(image.size),frames=frames)
    rears={}
    for gender,split_y in (('Nam',632),('Nu',626)):
        file=f'Character/Expressions/Rear/{gender}.png'
        image=Image.open(ROOT/file).convert('RGBA')
        split_x=image.width//2
        for index,folder in enumerate(('Kiem','Liem','Thuong','Quat')):
            x=split_x*(index%2);y=split_y*(index//2)
            cell=[x,y,split_x,(split_y if index<2 else image.height-split_y)]
            rect,anchor=measure(image,cell)
            rears[f'{folder}/{gender}']=dict(file=file,size=list(image.size),rect=rect,anchor=anchor,pixelAspect=1)
    data=dict(version=2,type='whole-character',directions=['truoc','trai','phai'],atlases=atlases,rears=rears)
    (ROOT/'Character/Expressions/manifest.json').write_text(json.dumps(data,ensure_ascii=False,separators=(',',':'))+'\n',encoding='utf-8')
    (ROOT/'js/35l-expression-frames.js').write_text('/* Generated by tests/build_expression_manifest.py: whole-body frames only. */\nwindow.characterExpressionFrames='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
    print('Measured 8 expression atlases / 240 expression frames + 8 complete rear sprites; source PNGs unchanged.')

if __name__=='__main__': main()
